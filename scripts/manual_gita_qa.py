def _check_verse_verification(
    question: str,
    result: FinalQAResult | None,
) -> tuple[str, str]:
    """Check whether citations correspond to requested verse based on provenance."""
    if result is None:
        return "failed", "UNAVAILABLE"

    pipeline_status = (
        "citation_resolved"
        if result.status is FinalQAStatus.CITATION_RESOLVED
        else ("unmarked" if result.status is FinalQAStatus.UNMARKED else "failed")
    )

    # Check if question requests an exact chapter and verse
    match_dot = re.search(r"\b([1-9]|1[0-8])\.([0-9]{1,2})\b", question)
    match_text = re.search(
        r"Chapter\s+([1-9]|1[0-8]).*?(?:Verse|Text)\s+([0-9]{1,2})", question, re.IGNORECASE
    )

    req_chap: int | None = None
    req_verse: int | None = None
    if match_dot:
        req_chap = int(match_dot.group(1))
        req_verse = int(match_dot.group(2))
    elif match_text:
        req_chap = int(match_text.group(1))
        req_verse = int(match_text.group(2))

    if req_chap is None or req_verse is None:
        return pipeline_status, "N/A (Conceptual/Topic Query)"

    if not result.citations:
        return pipeline_status, "UNAVAILABLE (No citations resolved)"

    words = _CHAPTER_NUM_TO_WORDS.get(req_chap, (str(req_chap),))
    verse_patterns = [
        f"{req_chap}.{req_verse}",
        f"TEXT {req_verse}",
        f"VERSE {req_verse}",
        f"TEXTS {req_verse}",
    ]

    matched = False
    retrieved_provenances: list[str] = []
    for citation in result.citations:
        heading_joined = " ".join(citation.heading_path).upper()
        quote_upper = citation.verbatim_quote.upper()
        retrieved_provenances.append(f"{citation.heading_path} (page {citation.page_number})")

        has_chap = (
            any(f"CHAPTER {w}" in heading_joined for w in words)
            or f"BG {req_chap}" in heading_joined
        )
        has_verse = any(p in heading_joined or p in quote_upper for p in verse_patterns)

        if has_chap and has_verse:
            matched = True
            break

    if matched:
        return pipeline_status, f"VERIFIED (Retrieved Chapter {req_chap}, Verse {req_verse})"
    if retrieved_provenances:
        return (
            pipeline_status,
            f"NOT VERIFIED (Retrieved {len(result.citations)} non-matching citations)",
        )
    return pipeline_status, "UNAVAILABLE"


async def run_qa(
    engine: KnowledgeEngine,
    question: str,
    title: str,
    chunks: Sequence[Chunk],
    notebook_id: UUID,
    source_id: UUID,
    headings: tuple[str, ...],
    context_tokens: int,
    max_output_tokens: int,
) -> tuple[FinalQAResult | None, float, dict[str, object]]:
    """Execute a single query through the complete Mnemo Phase 0-6 RAG pipeline."""
    session_id = uuid4()
    user_turn_id = uuid4()
    assistant_turn_id = uuid4()
    now = datetime.now(UTC)

    with contextlib.suppress(Exception):
        await engine.storage.upsert_notebook(
            Notebook(
                notebook_id=notebook_id,
                created_at=now,
                updated_at=now,
                title="Manual Gita QA",
            )
        )

    with contextlib.suppress(Exception):
        await engine.storage.upsert_source(
            Source(
                source_id=source_id,
                notebook_id=notebook_id,
                document_id=chunks[0].document_id,
                created_at=now,
            )
        )

    user_turn = Turn(
        turn_id=user_turn_id,
        session_id=session_id,
        sequence=0,
        role=TurnRole.USER,
        content=question,
        created_at=now,
    )
    await engine.storage.upsert_session(
        Session(
            session_id=session_id,
            notebook_id=notebook_id,
            created_at=now,
            updated_at=now,
            title="Manual Gita QA Session",
            turns=(user_turn,),
        )
    )

    request = FinalQARequest(
        query=question,
        metadata_filter=MetadataFilter(
            notebook_id=notebook_id,
            source_ids=(source_id,),
            doc_types=(DocType.BOOK,),
        ),
        global_limit=6,
        context_budget=min(context_tokens - 2000, 6000),
        system_prompt="Answer only from the supplied Bhagavad Gita context.",
        max_output_tokens=max_output_tokens,
        session_id=session_id,
        user_turn_id=user_turn_id,
        assistant_turn_id=assistant_turn_id,
        table_of_contents=headings,
        source_titles=(title,),
        document_labels=(
            DocumentContextLabel(
                document_id=chunks[0].document_id,
                version_id=chunks[0].version_id,
                title=title,
            ),
        ),
    )

    start_time = time.perf_counter()
    try:
        result = await engine.final_qa.execute(request)
        latency = time.perf_counter() - start_time
        meta: dict[str, object] = {
            "session_id": str(session_id),
            "user_turn_id": str(user_turn_id),
            "assistant_turn_id": str(assistant_turn_id),
        }
        return result, latency, meta
    except Exception as exc:
        latency = time.perf_counter() - start_time
        meta = {"error": str(exc), "session_id": str(session_id)}
        return None, latency, meta


def print_qa_report(
    question: str,
    result: FinalQAResult | None,
    latency: float,
    context_tokens: int,
    max_output_tokens: int,
    title: str,
    target_doc_id: UUID,
    target_ver_id: UUID,
    meta: dict[str, object],
) -> dict[str, object]:
    """Print the complete human-readable evaluation report in exact required format."""
    print("\n" + "=" * 60)
    print("QUESTION")
    print("=" * 60)
    print(question)

    print("\n" + "=" * 60)
    print("GEMMA 4:e4b ANSWER")
    print("=" * 60)

    if result is None or not result.answer or not result.answer.strip():
        print("MODEL PRODUCED NO FINAL CONTENT")
        print("\nDiagnostic metadata:")
        print(f"  - error: {meta.get('error', 'Empty content returned by LLM')}")
        print(f"  - requested context_size: {context_tokens}")
        print(f"  - max_output_tokens: {max_output_tokens}")
        return {"non_empty": False, "markers_valid": False, "all_resolved": False}

    # Print EXACT answer verbatim - never private thinking
    print(result.answer)

    print("\n" + "=" * 60)
    print("CITATION RESOLUTION")
    print("=" * 60)

    if not result.citations:
        print("(No citations resolved)")
    else:
        for citation in result.citations:
            chapter = _extract_chapter(citation.heading_path)
            verse_heading = _extract_verse_heading(citation.heading_path)
            print(f"[source:{citation.source_number}]")
            print(f"  document: {title}")
            print(f"  chapter: {chapter}")
            print(f"  verse/heading if available: {verse_heading}")
            print(f"  page: {citation.page_number}")
            print(f"  chunk_id: {citation.chunk_id}")
            print(f"  citation_id: {citation.citation_id}")
            print(f"  canonical quote: {citation.verbatim_quote!r}")
            print()

    # Extract pipeline metadata
    answer_res = result.citation_result.answer_result
    ctx_res = answer_res.context_result
    gen_evidence = answer_res.generation_evidence
    rerank_res = ctx_res.rerank_result
    fusion_res = rerank_res.fusion_result

    prompt_tokens = ctx_res.context_tokens
    answer_tokens = gen_evidence.answer_token_count if gen_evidence is not None else 0
    retrieved_candidates = len(fusion_res.results)
    selected_context_items = len(ctx_res.items)
    compressed_items = sum(1 for it in ctx_res.items if it.kind is ContextItemKind.COMPRESSED)
    citation_count = len(result.citations)

    print("=" * 60)
    print("PIPELINE METADATA")
    print("=" * 60)
    print(f"- model: {MODEL}")
    print(f"- context size: {context_tokens}")
    print(f"- prompt tokens: {prompt_tokens}")
    print(f"- answer tokens: {answer_tokens}")
    print(f"- number of retrieved candidates: {retrieved_candidates}")
    print(f"- number of selected context items: {selected_context_items}")
    print(f"- number of compressed items: {compressed_items}")
    print(f"- number of citations: {citation_count}")
    print(f"- total latency: {latency:.2f}s")

    # Automated Checks & Verification
    pipeline_status, content_verification = _check_verse_verification(question, result)

    non_empty = bool(result.answer and result.answer.strip())
    all_resolved = result.status in (FinalQAStatus.CITATION_RESOLVED, FinalQAStatus.NO_CONTEXT)
    markers_valid = all_resolved
    citations_persisted = result.citation_result.persisted
    provenance_preserved = all(
        c.document_id == target_doc_id and c.version_id == target_ver_id for c in result.citations
    )
    valid_source_nums = {item.source_number for item in ctx_res.items}
    no_unknown = all(c.source_number in valid_source_nums for c in result.citations)
    within_bound = answer_tokens <= max_output_tokens

    print("\n" + "=" * 60)
    print("VERIFICATION & CHECKS")
    print("=" * 60)
    print(f"PIPELINE STATUS: {pipeline_status}")
    print(f"CONTENT VERIFICATION: {content_verification}")
    print()
    print(f"[{'PASS' if non_empty else 'FAIL'}] Non-empty answer")
    print(f"[{'PASS' if markers_valid else 'FAIL'}] Citation markers syntactically valid")
    print(f"[{'PASS' if all_resolved else 'FAIL'}] All markers resolve")
    print(f"[{'PASS' if citations_persisted else 'FAIL'}] Citations persisted")
    print(f"[{'PASS' if provenance_preserved else 'FAIL'}] Provenance preserved")
    print(f"[{'PASS' if no_unknown else 'FAIL'}] No unknown source numbers")
    print(f"[{'PASS' if within_bound else 'FAIL'}] Answer within output bound")
    print("\nHuman evaluation required: YES")
    print("=" * 60 + "\n")

    return {
        "non_empty": non_empty,
        "markers_valid": markers_valid,
        "all_resolved": all_resolved,
        "citations_persisted": citations_persisted,
        "provenance_preserved": provenance_preserved,
        "no_unknown": no_unknown,
        "within_bound": within_bound,
        "tokens": answer_tokens,
        "latency": latency,
        "pipeline_status": pipeline_status,
        "content_verification": content_verification,
    }


async def _run_batch_questions(
    engine: KnowledgeEngine,
    questions: dict[str, str],
    group_name: str,
    title: str,
    chunks: Sequence[Chunk],
    notebook_id: UUID,
    source_id: UUID,
    headings: tuple[str, ...],
    context_size: int,
    max_output: int,
    target_doc_id: UUID,
    target_ver_id: UUID,
) -> None:
    """Run a dictionary of questions in batch mode and display individual + summary reports."""
    total = len(questions)
    results: list[dict[str, object]] = []

    print(f"\n[Batch] Executing {group_name} ({total} questions) sequentially...\n")

    for i, (code, q) in enumerate(questions.items(), 1):
        print(f"\n>>> [{code}] Running Question {i}/{total}: {q}")
        res, lat, meta = await run_qa(
            engine,
            q,
            title,
            chunks,
            notebook_id,
            source_id,
            headings,
            context_size,
            max_output,
        )
        checks = print_qa_report(
            q,
            res,
            lat,
            context_size,
            max_output,
            title,
            target_doc_id,
            target_ver_id,
            meta,
        )
        results.append(checks)

    # Batch Summary
    success_count = sum(1 for r in results if r.get("non_empty"))
    failed_count = total - success_count
    resolved_count = sum(1 for r in results if r.get("all_resolved") and r.get("non_empty"))
    fail_citations = total - resolved_count
    verified_count = sum(1 for r in results if "VERIFIED" in str(r.get("content_verification", "")))
    valid_tokens = [int(str(r["tokens"])) for r in results if "tokens" in r]
    avg_tokens = sum(valid_tokens) / len(valid_tokens) if valid_tokens else 0.0
    valid_lats = [float(str(r["latency"])) for r in results if "latency" in r]
    avg_lat = sum(valid_lats) / len(valid_lats) if valid_lats else 0.0

    print("\n" + "=" * 60)
    print(f"BATCH SUMMARY — {group_name}")
    print("=" * 60)
    print(f"Questions attempted: {total}")
    print(f"Successful answers: {success_count}")
    print(f"Failed answers: {failed_count}")
    print(f"Citation-resolved answers: {resolved_count}")
    print(f"Citation failures: {fail_citations}")
    print(f"Content-verified answers: {verified_count}")
    print()
    print(f"Average latency: {avg_lat:.2f}s")
    print(f"Average answer tokens: {avg_tokens:.1f}")
    print("=" * 60 + "\n")


