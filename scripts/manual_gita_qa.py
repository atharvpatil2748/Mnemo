async def _ensure_indexed(
    config: MnemoConfig, force_reindex: bool = False
) -> tuple[tuple[Chunk, ...], str, UUID, UUID]:
    """Ensure the Bhagavad Gita dataset is parsed and embedded into storage."""
    notebook_id = uuid5(NAMESPACE_URL, "mnemo-manual-qa:notebook")
    source_id = uuid5(NAMESPACE_URL, "mnemo-manual-qa:source")
    db_path = DATA_DIR / "mnemo.db"
    token_counter = O200KBaseTokenCounter(_tokenizer_asset())
    bootstrap_registry = _registry(config)

    if not force_reindex and db_path.exists():
        storage = bootstrap_registry.resolve_storage("primary")
        if storage is not None:
            await storage.open()
            try:
                page = await storage.list_documents(status=None, limit=1, cursor=None)
                if page.items:
                    doc = page.items[0]
                    current = next(
                        v for v in doc.versions if v.version_id == doc.current_version_id
                    )
                    title = current.metadata.title or "Bhagavad Gita"
                    parsed = await storage.get_parsed_document(current.version_id)
                    if parsed is not None:
                        from mnemo.chunkers import ChunkerDispatcher
                        from mnemo.interfaces import ChunkingContext, ChunkingOptions

                        dispatcher = ChunkerDispatcher(bootstrap_registry, token_counter)
                        ctx = ChunkingContext(
                            document_version=current,
                            options=ChunkingOptions(target_tokens=400, max_tokens=500),
                        )
                        chunks = dispatcher.dispatch(parsed, ctx)
                        await storage.close()
                        return chunks, title, notebook_id, source_id
            finally:
                await storage.close()

    import shutil

    if DATA_DIR.exists():
        for item in DATA_DIR.iterdir():
            if item.is_dir():
                shutil.rmtree(item)
            else:
                item.unlink()
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    print("[Setup] Freshly indexing Bhagavad Gita golden corpus into data/manual-gita-qa ...")
    bootstrap_registry = _registry(config)
    _m4, chunks, bootstrap_storage = await _run_m4(bootstrap_registry, config)
    document = await bootstrap_storage.get_document(chunks[0].document_id)
    if document is None:
        raise RuntimeError("Failed to retrieve parsed document")
    current = next(v for v in document.versions if v.version_id == document.current_version_id)
    title = current.metadata.title or "Bhagavad Gita"

    now = datetime.now(UTC)
    notebook = Notebook(
        notebook_id=notebook_id,
        title="Manual Bhagavad Gita QA",
        created_at=now,
        updated_at=now,
    )
    source = Source(
        source_id=source_id,
        notebook_id=notebook_id,
        document_id=chunks[0].document_id,
        created_at=now,
    )
    await bootstrap_storage.upsert_notebook(notebook)
    await bootstrap_storage.upsert_source(source)

    print("[Setup] Generating embeddings with nomic-embed-text into Qdrant ...")
    await bootstrap_registry.execute_startup_hooks()
    provider = bootstrap_registry.resolve_embedding_provider("primary")
    if provider is None:
        raise RuntimeError("Primary embedding provider not registered")

    from mnemo.embeddings.cached import CachedEmbeddingProvider
    from mnemo.embeddings.embedder import EmbedderModule
    from mnemo.storage.cache import SQLiteEmbeddingCache

    cache_path = DATA_DIR / "embedding-cache.db"
    cache = SQLiteEmbeddingCache(cache_path)
    await cache.initialize()
    cached_provider = CachedEmbeddingProvider(provider, cache)
    embedder = EmbedderModule(cached_provider, max_concurrency=4)

    embedded = await embedder.embed_chunks(chunks[:1000])
    await bootstrap_storage.upsert_chunks(embedded)
    print(f"[Setup] Ingestion complete: {len(chunks)} chunks, {len(embedded)} embedded & indexed.")
    await bootstrap_storage.close()
    return chunks, title, notebook_id, source_id


def _extract_chapter(heading_path: Sequence[str]) -> str:
    for heading in heading_path:
        upper = heading.upper()
        if "CHAPTER" in upper:
            return heading
    if len(heading_path) > 1:
        return heading_path[1]
    return heading_path[0] if heading_path else "Unknown"


def _extract_verse_heading(heading_path: Sequence[str]) -> str:
    for heading in reversed(heading_path):
        upper = heading.upper()
        if "TEXT" in upper or "VERSE" in upper:
            return heading
    return heading_path[-1] if heading_path else "Unknown"


